import threading
from pathlib import Path
import webbrowser

import bpy
from .bridge import create_server, PUBLIC_URL

server = None
token = None

def start_gateway():
    global server, token
    if server is None:
        output = Path.home() / "Atelier 3D" / "outputs"
        server, token = create_server(blender=bpy.app.binary_path, output=output)
        threading.Thread(target=server.serve_forever, daemon=True).start()

def stop_gateway():
    global server, token
    if server:
        server.shutdown()
        server.chatgpt.close()
        server.server_close()
        server, token = None, None

class ATELIER_OT_open(bpy.types.Operator):
    bl_idname = "atelier.open_app"
    bl_label = "Open Atelier 3D"
    local: bpy.props.BoolProperty(default=False)

    def execute(self, context):
        try:
            start_gateway()
        except OSError:
            self.report({"ERROR"}, "Port 8765 is busy. Close the previous Atelier gateway and retry.")
            return {"CANCELLED"}
        address = f"http://127.0.0.1:{server.server_port}/" if self.local else PUBLIC_URL
        webbrowser.open(f"{address}#pair={token}")
        self.report({"INFO"}, "Atelier gateway is running")
        return {"FINISHED"}

class ATELIER_OT_copy(bpy.types.Operator):
    bl_idname = "atelier.copy_pairing"
    bl_label = "Copy connection code"

    def execute(self, context):
        if token:
            context.window_manager.clipboard = token
        return {"FINISHED"}

class ATELIER_OT_stop(bpy.types.Operator):
    bl_idname = "atelier.stop_gateway"
    bl_label = "Stop gateway"

    def execute(self, context):
        if server and any(job["state"] == "running" for job in server.work.jobs.values()):
            self.report({"WARNING"}, "A render job is running. Wait for it to finish.")
            return {"CANCELLED"}
        stop_gateway()
        return {"FINISHED"}

class ATELIER_PT_gateway(bpy.types.Panel):
    bl_label = "Atelier 3D"
    bl_idname = "ATELIER_PT_gateway"
    bl_space_type = "VIEW_3D"
    bl_region_type = "UI"
    bl_category = "Atelier 3D"

    def draw(self, context):
        layout = self.layout
        layout.label(text="Gateway running" if server else "Gateway stopped")
        layout.operator("atelier.open_app", text="Start gateway and open app", icon="URL")
        layout.operator("atelier.open_app", text="Open local app").local = True
        if server:
            layout.operator("atelier.copy_pairing")
            layout.operator("atelier.stop_gateway")

CLASSES = (ATELIER_OT_open, ATELIER_OT_copy, ATELIER_OT_stop, ATELIER_PT_gateway)

def register():
    for cls in CLASSES:
        bpy.utils.register_class(cls)

def unregister():
    stop_gateway()
    for cls in reversed(CLASSES):
        bpy.utils.unregister_class(cls)
