def archive(files):
    buffer = BytesIO()
    with ZipFile(buffer,"w") as package:
        for path, content in files.items():
            package.writestr(ZipInfo(path),content,compress_type=ZIP_DEFLATED)
    return base64.b64encode(buffer.getvalue()).decode()


def main():
    base = {name:(ROOT / name).read_bytes() for name in ("index.html","bridge.py","chatgpt.py")}
    blender = archive({"atelier_3d_gateway/" + name:value
                       for name,value in (base | {"__init__.py":ADDON}).items()})
    gateway = archive(base | {"start_gateway.cmd":WINDOWS.replace("\n","\r\n"), "HUONG_DAN.txt":GATEWAY_README})
    module = "// Generated by package_installers.py.\n"
    for name,value in (("blender",blender),("gateway",gateway)):
        chunks = [value[start:start+100] for start in range(0,len(value),100)]
        module += "export const " + name + " = [\n"
        module += "".join("  " + json.dumps(chunk) + ",\n" for chunk in chunks)
        module += "].join(\"\");\n"
    (ROOT / "installers.js").write_text(module,encoding="utf-8")


if __name__ == "__main__":
    main()
